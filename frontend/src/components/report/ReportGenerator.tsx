/**
 * Report Generator Component.
 *
 * Generates professional engineering reports.
 */

import type { OpticalSystem, AnalysisResult, LengthUnit } from '../../types';
import { fmtLen, fmtNum, fromMeters, LENGTH_UNIT_LABELS } from '../../types';

interface ReportGeneratorProps {
  system: OpticalSystem;
  analysis: AnalysisResult | null;
  displayUnit: LengthUnit;
}

export function ReportGenerator({ system, analysis, displayUnit }: ReportGeneratorProps) {
  const unitLabel = LENGTH_UNIT_LABELS[displayUnit];
  
  const generateReport = (): string => {
    const lines: string[] = [];
    
    lines.push('# Optical Design Report');
    lines.push(`Generated: ${new Date().toLocaleString()}`);
    lines.push(`Engine: AI Optical Design Engineer v0.2.0`);
    lines.push('');
    
    lines.push('## System Prescription');
    lines.push('| # | Type | Label | Position | Material | Aperture |');
    lines.push('|---|------|-------|----------|----------|----------|');
    
    system.components.forEach((comp, i) => {
      const pos = fromMeters(comp.position, displayUnit).toFixed(4);
      const aperture = comp.type === 'thin_lens' 
        ? fromMeters(comp.aperture_diameter, displayUnit).toFixed(4)
        : comp.type === 'thick_lens'
          ? fromMeters(comp.aperture_diameter, displayUnit).toFixed(4)
          : comp.type === 'aperture'
            ? fromMeters(comp.diameter, displayUnit).toFixed(4)
            : '-';
      const material = comp.type === 'thin_lens' || comp.type === 'thick_lens' ? comp.material : '-';
      lines.push(`| ${i + 1} | ${comp.type} | ${comp.id} | ${pos} | ${material} | ${aperture} |`);
    });
    
    lines.push('');
    
    if (analysis) {
      lines.push('## Performance Analysis');
      lines.push(`- Effective Focal Length: ${fmtLen(analysis.effective_focal_length, displayUnit, 4)} ${unitLabel}`);
      lines.push(`- Magnification: ${fmtNum(analysis.magnification, 4)}x`);
      lines.push(`- F-number: f/${fmtNum(analysis.f_number, 2)}`);
      lines.push(`- Numerical Aperture: ${analysis.numerical_aperture.toFixed(4)}`);
      lines.push(`- RMS Spot Radius: ${fromMeters(analysis.rms_spot_radius, displayUnit).toFixed(6)} ${unitLabel}`);
      lines.push(`- Image Distance: ${fmtLen(analysis.image_distance, displayUnit, 4)} ${unitLabel}`);
      lines.push(`- Working Distance: ${fmtLen(analysis.working_distance, displayUnit, 4)} ${unitLabel}`);
      lines.push(`- Image Type: ${analysis.is_image_real ? 'Real' : 'Virtual'}`);
      lines.push(`- Image Orientation: ${analysis.is_image_inverted ? 'Inverted' : 'Upright'}`);
      lines.push('');
    }
    
    lines.push('## Assumptions');
    lines.push('- Paraxial approximation for first-order analysis');
    lines.push('- Sequential ray tracing only');
    lines.push('- Monochromatic analysis');
    lines.push('- Ideal surfaces (no defects)');
    lines.push('- Perfect alignment');
    
    return lines.join('\n');
  };
  
  const report = generateReport();
  
  const exportHtml = () => {
    const html = `<!DOCTYPE html>
<html><head><title>Optical Design Report</title>
<style>
body{font-family:Arial,sans-serif;margin:40px;}
h1{color:#1e40af;}
h2{color:#374151;border-bottom:1px solid #e5e7eb;padding-bottom:8px;}
table{border-collapse:collapse;width:100%;}
th,td{border:1px solid #e5e7eb;padding:8px;text-align:left;}
th{background:#f3f4f6;}
pre{background:#f9fafb;padding:16px;border-radius:4px;}
</style></head><body>
<h1>Optical Design Report</h1>
<p><em>Generated by AI Optical Design Engineer</em></p>
${report.split('\n').map(line => {
  if (line.startsWith('# ')) return `<h1>${line.slice(2)}</h1>`;
  if (line.startsWith('## ')) return `<h2>${line.slice(3)}</h2>`;
  if (line.startsWith('| ')) {
    const cells = line.split('|').filter(c => c.trim());
    if (cells.every(c => c.trim().match(/^[-]+$/))) return '';
    const tag = report.split('\n').indexOf(line) < 5 ? 'th' : 'td';
    return `<tr>${cells.map(c => `<${tag}>${c.trim()}</${tag}>`).join('')}</tr>`;
  }
  if (line.startsWith('- ')) return `<li>${line.slice(2)}</li>`;
  return `<p>${line}</p>`;
}).join('\n')}
</body></html>`;
    
    const blob = new Blob([html], { type: 'text/html' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'optical-design-report.html';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };
  
  const exportMarkdown = () => {
    const blob = new Blob([report], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'optical-design-report.md';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="p-4 border-t border-gray-200">
      <div className="flex justify-between items-center mb-3">
        <h3 className="text-sm font-semibold text-gray-700">Engineering Report</h3>
        <div className="flex gap-2">
          <button onClick={exportHtml} className="px-3 py-1 text-xs bg-blue-500 text-white rounded hover:bg-blue-600">
            Export HTML
          </button>
          <button onClick={exportMarkdown} className="px-3 py-1 text-xs bg-gray-500 text-white rounded hover:bg-gray-600">
            Export Markdown
          </button>
        </div>
      </div>
      
      <div className="border border-gray-200 rounded bg-gray-50 p-4 max-h-96 overflow-y-auto">
        <pre className="text-xs text-gray-700 whitespace-pre-wrap font-mono">
          {report}
        </pre>
      </div>
    </div>
  );
}
