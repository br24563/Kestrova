/**
 * ISO 10110 element drawings of the prescription: a to-scale section and
 * the surface and material data of every glass element. Codes the design
 * does not set (surface imperfections, bubbles, ...) can be filled in.
 */
import { useState } from "react";
import type { LensData } from "../../types";
import { lensDrawings } from "../../api";
import type { ElementDrawing } from "../../api";

const NOTE_FIELDS: { key: string; label: string; placeholder: string }[] = [
  { key: "5/", label: "5/ imperfections", placeholder: "5/3×0.16" },
  { key: "irregularity", label: "Irregularity (fringes)", placeholder: "1" },
  { key: "1/", label: "1/ bubbles", placeholder: "1/2×0.1" },
  { key: "2/", label: "2/ inhomogeneity", placeholder: "2/1;1" },
  { key: "0/", label: "0/ stress birefringence", placeholder: "0/20" },
];

function Column({ title, rows }: { title: string; rows: [string, string][] }) {
  return (
    <table className="border border-gray-200 rounded">
      <caption className="text-left font-semibold text-gray-700">
        {title}
      </caption>
      <tbody>
        {rows.map(([k, v]) => (
          <tr key={k} className="border-t border-gray-100">
            <th className="px-2 py-0.5 text-left font-medium text-gray-600 bg-gray-50">
              {k}
            </th>
            <td className="px-2 py-0.5 font-mono">{v}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

export function DrawingsPanel({ lens }: { lens: LensData | null }) {
  const [notes, setNotes] = useState<Record<string, string>>({});
  const [margin, setMargin] = useState("1");
  const [drawings, setDrawings] = useState<ElementDrawing[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [running, setRunning] = useState(false);

  if (!lens)
    return (
      <p className="p-4 text-xs text-gray-500">
        Element drawings work on the lens data (open or convert a lens in the
        Lens Data Editor).
      </p>
    );

  const draw = async () => {
    const m = Number(margin);
    if (!Number.isFinite(m) || m < 0) {
      setError("The edge margin must be 0 or more");
      return;
    }
    setRunning(true);
    setError(null);
    try {
      const filled = Object.fromEntries(
        Object.entries(notes).filter(([, v]) => v.trim()),
      );
      const out = await lensDrawings(lens, {
        notes: filled,
        edgeMargin: m * 1e-3,
      });
      setDrawings(out.drawings);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Drawing failed");
    } finally {
      setRunning(false);
    }
  };

  return (
    <div className="p-4 space-y-3 text-xs" data-testid="drawings">
      <div className="flex flex-wrap items-center gap-3 text-gray-600">
        <h3 className="text-sm font-semibold text-gray-700 mr-auto">
          Element drawings (ISO 10110)
        </h3>
        <label
          className="flex items-center gap-1"
          title="Outer diameter minus the clear aperture"
        >
          Edge margin (mm)
          <input
            aria-label="Edge margin"
            value={margin}
            onChange={(e) => setMargin(e.target.value)}
            className="w-12 border border-gray-200 rounded px-1 py-0.5 text-right"
          />
        </label>
        <button
          onClick={draw}
          disabled={running}
          className="px-3 py-1 bg-optical-600 text-white rounded hover:bg-optical-700 disabled:opacity-50"
        >
          {running ? "Drawing..." : "Draw"}
        </button>
      </div>
      <div className="flex flex-wrap gap-3 text-gray-600">
        {NOTE_FIELDS.map((f) => (
          <label key={f.key} className="flex items-center gap-1">
            {f.label}
            <input
              aria-label={f.label}
              placeholder={f.placeholder}
              value={notes[f.key] ?? ""}
              onChange={(e) => setNotes({ ...notes, [f.key]: e.target.value })}
              className="w-20 border border-gray-200 rounded px-1 py-0.5"
            />
          </label>
        ))}
      </div>
      {error && (
        <p className="text-red-500" role="alert">
          {error}
        </p>
      )}
      {drawings && drawings.length === 0 && (
        <p className="text-gray-500">No glass elements (mirrors only).</p>
      )}
      {drawings?.map((d) => (
        <section
          key={d.surfaces.join("-")}
          className="border border-gray-200 rounded p-2 space-y-2"
          data-testid="element-drawing"
        >
          <h4 className="font-semibold text-gray-700">
            {d.name}: S{d.surfaces[0]}–S{d.surfaces[1]}, {d.glass}
          </h4>
          <div className="flex flex-wrap gap-3 items-start">
            {/* SVG generated by the engine from numbers only */}
            <div dangerouslySetInnerHTML={{ __html: d.svg }} />
            <Column title="Left surface" rows={d.left} />
            <Column title="Material" rows={d.material} />
            <Column title="Right surface" rows={d.right} />
          </div>
        </section>
      ))}
      {drawings && drawings.length > 0 && (
        <p className="text-gray-400">
          Dimensions in mm. 3/ power from the tolerance set&apos;s fringes, 4/
          from the surface and element tilts; — = not set by the design. The
          Report tab includes these drawings.
        </p>
      )}
    </div>
  );
}
